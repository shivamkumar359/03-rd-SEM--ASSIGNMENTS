import numpy as np

# Create a 3x4 matrix containing values from 1 to 12
matrix = np.arange(1, 13).reshape(3, 4)

# Display the original matrix
print("Original Matrix:")
print(matrix)

# Extract the first two rows and middle two columns
subarray = matrix[0:2, 1:3]

print("\nExtracted 2x2 Subarray:")
print(subarray)

# Modify the first element of the extracted subarray
subarray[0, 0] = 77

# Display the modified original matrix
print("\nFinal Original Matrix After Modification:")
print(matrix)